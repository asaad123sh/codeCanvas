const phpString = (value: string) =>
  String(value ?? '').replace(/\\/g, '\\\\').replace(/'/g, "\\'");

export function slugify(value: string): string {
  return (
    String(value || '')
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '')
      .slice(0, 40) || 'webcraft-site'
  );
}

