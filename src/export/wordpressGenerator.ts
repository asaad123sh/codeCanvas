/** WordPress pages are addressed by their slug through `get_page_by_path`. */
const wpUrl: PageUrlFn = (page) => '/' + pageFileSlug(page) + '/';

/**
 * Render one builder page inside a WordPress template.
 *
 * Kept as a shortcode-free PHP function so the markup is a plain string
 * replacement: no shortcode parsing, no escaping surprises.
 */
function wpPageRenderBlock(site: SiteModel, page: SitePage, themeName: string, slug: string): string {
  const fn = phpFunctions(slug.replace(/-/g, '_'));
  const description = page.config.metaTags?.description || '';
  return `
if (!function_exists('${fn}render_page')) {
    /**
     * Output the markup for one generated page.
     *
     * @param string $page_id Builder page id.
     * @param array  $pages  id => [slug, name, description].
     */
    function ${fn}render_page(string $page_id, array $pages): void
    {
        if (!isset($pages[$page_id])) {
            return;
        }
        $entry = $pages[$page_id];
        $description = (string) $entry['description'];
        if ($description !== '' && !defined('WEB_CRAFT_DESCRIPTION')) {
            define('WEB_CRAFT_DESCRIPTION', $description);
        }
        echo $entry['markup'];
    }
}

/** id => [slug, name, description, markup] for every page in the builder. */
function ${fn}pages(): array
{
    return ${phpJson(
      siteContentPages(site).reduce<Record<string, unknown>>((acc, page) => {
        acc[page.id] = {
          slug: pageFileSlug(page),
          name: page.name,
          description: page.config.metaTags?.description || '',
          markup: renderSitePage(site, page, wpUrl),
        };
        return acc;
      }, {}),
      'WEBCRAFT_PAGES'
    )};
}
`;
}

