const phpString = (value: string) =>
  String(value ?? '').replace(/\\/g, '\\\\').replace(/'/g, "\\'");

/**
 * Embed a JS value in generated PHP.
 *
 * JSON is not a PHP literal, so the data goes through a nowdoc and
 * `json_decode`: no escaping can ever corrupt a title or a page slug.
 */
export const phpJson = (value: unknown, label = 'WEBCRAFT_JSON'): string =>
  `json_decode(<<<'${label}'\n${JSON.stringify(value, null, 4)}\n${label}\n, true)`;

