/** `about` -> `about.php`, home -> `index.php`. */
const phpUrl: PageUrlFn = (page) => `${pageFileSlug(page)}.php`;

/**
 * One thin file per page, all sharing `bootstrap.php`.
 *
 * Each page file only names itself; the bootstrap owns auth, form handling,
 * search and the session/CSRF fill-in, so a 12-page site stays maintainable.
 */
function phpPageFile(page: SitePage, site: SiteModel): string {
  return `<?php
/**
 * ${page.name} - generated by WebCraft Pro
 */
declare(strict_types=1);

require __DIR__ . '/bootstrap.php';

$webcraft_page_id = '${phpString(page.id)}';
$webcraft_markup = <<<'WEBCRAFT_HTML'
${renderSitePage(site, page, phpUrl)}
WEBCRAFT_HTML;

wb_render_page($webcraft_markup, '${phpString(page.id)}', '${phpString(page.name)}');
`;
}

function generateSitePHP(
  site: SiteModel,
  databaseSchema: DatabaseSchema,
  options: GeneratorOptions
): Record<string, string> {
  const files: Record<string, string> = {};
  const pages = siteContentPages(site);
  const hasTables =
    (databaseSchema.tables || []).length > 0 && options.includeDatabase !== false;

  const css = generateSiteCSS(site, { customCSS: options.customCSS });
  const js =
    RUNTIME_HEADER +
    WIDGET_RUNTIME +
    COMMERCE_CLIENT_CORE +
    '\n\n/* ---- Store panels ---- */\n' +
    COMMERCE_PANELS +
    (options.customJS ? `\n\n/* Custom JS */\n${options.customJS}` : '') +
    '\n';

  // SEO for every page, keyed by page id, so the bootstrap can look one up.
  const seo: Record<string, { title: string; description: string; keywords: string; author: string }> = {};
  for (const page of pages) {
    seo[page.id] = {
      title: page.config.title || page.name,
      description: page.config.metaTags?.description || '',
      keywords: page.config.metaTags?.keywords || '',
      author: page.config.metaTags?.author || '',
    };
  }

  files['bootstrap.php'] = `<?php
/**
 * Shared runtime for every generated page.
 *
 * Owns auth, contact-form handling, search and the session/CSRF fill-in so the
 * per-page files stay tiny.
 */
declare(strict_types=1);

define('WB_DATA_DIR', __DIR__ . '/data');
if (!is_dir(WB_DATA_DIR)) {
    @mkdir(WB_DATA_DIR, 0775, true);
}
if (!file_exists(WB_DATA_DIR . '/secret.key')) {
    @file_put_contents(WB_DATA_DIR . '/secret.key', bin2hex(random_bytes(32)));
    @chmod(WB_DATA_DIR . '/secret.key', 0600);
}
define('WB_SECRET_FILE', trim((string) @file_get_contents(WB_DATA_DIR . '/secret.key')));

require __DIR__ . '/auth.php';
require __DIR__ . '/search.php';
require __DIR__ . '/commerce.php';

// The store runtime needs to know where the generated pages live so cart links,
// the product page and the COD confirmation all resolve.
$GLOBALS['WB_SHOP_SEED_FILE'] = WB_DATA_DIR . '/shop-seed.php';
$GLOBALS['WB_SHOP_FILE'] = WB_DATA_DIR . '/shop.json';
$GLOBALS['WB_SHOP_DIR'] = WB_DATA_DIR;
$GLOBALS['WB_SHOP_PATHS'] = ${phpJson(shopPaths(site), 'WEBCRAFT_SHOP_PATHS')};
if (function_exists('wb_shop_handle_api')) {
    wb_shop_handle_api();
}

/** Per-page SEO, filled in by the generator. */
function wb_seo(): array {
    return ${phpJson(seo, 'WEBCRAFT_SEO')};
}

${formHandlerBlock()}

/**
 * Print the finished document.
 *
 * $markup is the rendered page; $raw is the same markup before the session
 * panel is filled in, so the search index never contains a session name.
 */
function wb_render_page(string $markup, string $pageId, string $pageName): void {
    $sent = isset($_GET['sent']);
    $meta = wb_seo();
    $seo = $meta[$pageId] ?? array('title' => $pageName, 'description' => '', 'keywords' => '', 'author' => '');
    $currentUser = wb_session_user();

    $document = str_replace(
        array('<!--webcraft:session-->', '__WEBCRAFT_CSRF__', ' data-webcraft-session>'),
        array(
            $currentUser
                ? '<p class="wb-login__who">Signed in as <strong>' . htmlspecialchars($currentUser['name'], ENT_QUOTES) . '</strong></p>'
                  . '<form method="post" class="wb-login__logout"><input type="hidden" name="_webcraft_auth" value="logout">'
                  . '<input type="hidden" name="_wc_csrf" value="' . htmlspecialchars($_COOKIE[WEBCRAFT_CSRF_COOKIE] ?? '', ENT_QUOTES) . '">'
                  . '<button type="submit" class="wb-login__submit">Sign out</button></form>'
                : '<p class="wb-login__who">You are not signed in.</p>',
            htmlspecialchars($_COOKIE[WEBCRAFT_CSRF_COOKIE] ?? '', ENT_QUOTES),
            $currentUser ? ' data-webcraft-session>' : ' data-webcraft-session hidden>',
        ),
        $markup
    );

    // Search answers ?s=... with ranked results instead of the raw markup.
    $document = wb_render_search($document, '', $markup);
    // Fill the store blocks (catalog, featured products) server side.
    $document = wb_shop_hydrate($document);
    $title = $seo['title'];
    $description = $seo['description'];
    $keywords = $seo['keywords'];
    $author = $seo['author'];
    ?>
<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <title><?= htmlspecialchars($title) ?></title>
<?php if ($description !== ''): ?>
    <meta name="description" content="<?= htmlspecialchars($description) ?>">
<?php endif; ?>
<?php if ($keywords !== ''): ?>
    <meta name="keywords" content="<?= htmlspecialchars($keywords) ?>">
<?php endif; ?>
<?php if ($author !== ''): ?>
    <meta name="author" content="<?= htmlspecialchars($author) ?>">
<?php endif; ?>
    <link rel="stylesheet" href="style.css">
</head>
<body>
<?= $sent ? '<div class="wb-form-success">Thanks! Your message has been sent.</div>' : '' ?>
<?= $document ?>
    <script>window.__WB_SHOP__ = <?= json_encode(wb_shop_client_seed(), JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE) ?>;</script>
    <script src="script.js" defer></script>
</body>
</html>
<?php
}
`;

// Each page gets its own file; `index.php` is the home page.
  for (const page of pages) {
    files[`${pageFileSlug(page)}.php`] = phpPageFile(page, site);
  }
  if (!files['index.php']) {
    files['index.php'] = phpPageFile(pages[0], site);
  }

  files['style.css'] = css + '\n\n/* ---- Store ---- */\n' + COMMERCE_CSS + '\n';
  files['script.js'] = js;
  files['auth.php'] = `${PHP_AUTH}\n`;
  files['search.php'] = `${PHP_SEARCH}\n`;
  files['commerce.php'] = `${PHP_COMMERCE}\n`;
  files['data/shop-seed.php'] = shopSeedFile();
  files['data/.gitkeep'] = '';

  if (options.customHTML && options.customHTML.trim()) {
    files['partials/custom-html.html'] = options.customHTML;
  }

  if (hasTables) {
    files['migration.sql'] = generateMigrationSQL(databaseSchema, 'mysql');
  }

  const home = pages[0];
  files['README.md'] = `# ${home?.config.title || 'WebCraft Pro site'}

Multi-page PHP site generated by **WebCraft Pro** (${pages.length} page(s)).

## Run locally

\`\`\`bash
php -S localhost:8000
\`\`\`

## Pages

| Page | URL | File |
| --- | --- | --- |
${pages
  .map((p) => `| ${p.name} | \`/${pageFileSlug(p)}.php\` | \`${pageFileSlug(p)}.php\` |`)
  .join('\n')}

The nav bar and footer are separate documents (\`_nav\`, \`_footer\`) in the builder but
are rendered on every page by \`bootstrap.php\`.

## Custom code

Anything you wrote in the **Code** tab lives in \`style.css\` (CSS), \`script.js\`
(JavaScript) and \`partials/custom-html.html\` (HTML).
`;

  return files;
}

export function generatePHPProject(
  elements: Record<string, ElementNode>,
  rootIds: string[],
  pageConfig: PageConfig,
  databaseSchema: DatabaseSchema,
  options: GeneratorOptions = {},
  /** When present the whole site is exported (one file per page). */
  site?: SiteModel
): Record<string, string> {
  if (site && siteContentPages(site).length > 0) {
    return generateSitePHP(site, databaseSchema, options);
  }
  const files: Record<string, string> = {};
  const hasTables =
    (databaseSchema.tables || []).length > 0 && options.includeDatabase !== false;

  const document = renderDocument(elements, rootIds, options.customHTML || '');
  const css =
    generateCSS(elements, rootIds, pageConfig) +
    (options.customCSS ? `\n/* Custom CSS */\n${options.customCSS}\n` : '');
  const js =
    RUNTIME_HEADER +
    WIDGET_RUNTIME +
    (options.customJS ? `\n\n/* Custom JS */\n${options.customJS}` : '') +
    '\n';

  const title = pageConfig.title || 'My Website';
  const description = pageConfig.metaTags?.description || '';
  const keywords = pageConfig.metaTags?.keywords || '';
  const author = pageConfig.metaTags?.author || '';

  files['index.php'] = `<?php
/**
 * Generated by WebCraft Pro
 * Runs on PHP 7.4+ (Apache / Nginx / Caddy, or: php -S localhost:8000)
 */
declare(strict_types=1);

define('WB_DATA_DIR', __DIR__ . '/data');
if (!is_dir(WB_DATA_DIR)) {
    @mkdir(WB_DATA_DIR, 0775, true);
}
if (!file_exists(WB_DATA_DIR . '/secret.key')) {
    @file_put_contents(WB_DATA_DIR . '/secret.key', bin2hex(random_bytes(32)));
    @chmod(WB_DATA_DIR . '/secret.key', 0600);
}
define('WB_SECRET_FILE', trim((string) @file_get_contents(WB_DATA_DIR . '/secret.key')));

require __DIR__ . '/auth.php';
require __DIR__ . '/search.php';

$pageTitle   = '${phpString(title)}';
$description = '${phpString(description)}';
$keywords    = '${phpString(keywords)}';
$author      = '${phpString(author)}';
$sent        = isset($_GET['sent']);

// Auth posts (login / register / logout / reset) redirect back to this page.
if ($redirect = wb_handle_auth()) {
    header('Location: ' . $redirect);
    exit;
}
wb_ensure_csrf();
$currentUser = wb_session_user();

${formHandlerBlock()}

// The rendered design, kept in a nowdoc so quotes in the markup stay literal.
$webcraft_markup = <<<'WEBCRAFT_HTML'
${document}
WEBCRAFT_HTML;

// The session panel + CSRF token are filled server-side.
$document = str_replace(
    array('<!--webcraft:session-->', '__WEBCRAFT_CSRF__', ' data-webcraft-session>'),
    array(
        $currentUser
            ? '<p class="wb-login__who">Signed in as <strong>' . htmlspecialchars($currentUser['name'], ENT_QUOTES) . '</strong></p>'
              . '<form method="post" class="wb-login__logout"><input type="hidden" name="_webcraft_auth" value="logout">'
              . '<input type="hidden" name="_wc_csrf" value="' . htmlspecialchars($_COOKIE[WEBCRAFT_CSRF_COOKIE] ?? '', ENT_QUOTES) . '">'
              . '<button type="submit" class="wb-login__submit">Sign out</button></form>'
            : '<p class="wb-login__who">You are not signed in.</p>',
        htmlspecialchars($_COOKIE[WEBCRAFT_CSRF_COOKIE] ?? '', ENT_QUOTES),
        $currentUser ? ' data-webcraft-session>' : ' data-webcraft-session hidden>',
    ),
    $webcraft_markup
);

// Search: the page is split into sections and indexed, then ?s=... is answered
// with real ranked results instead of the raw markup. The index is built from
// the raw markup so the session panel above is not searchable.
$document = wb_render_search($document, '', $webcraft_markup);
?>
<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <title><?= htmlspecialchars($pageTitle) ?></title>
<?php if ($description !== ''): ?>
    <meta name="description" content="<?= htmlspecialchars($description) ?>">
<?php endif; ?>
<?php if ($keywords !== ''): ?>
    <meta name="keywords" content="<?= htmlspecialchars($keywords) ?>">
<?php endif; ?>
<?php if ($author !== ''): ?>
    <meta name="author" content="<?= htmlspecialchars($author) ?>">
<?php endif; ?>
    <link rel="stylesheet" href="style.css">
</head>
<body>
<?= $sent ? '<div class="wb-form-success">Thanks! Your message has been sent.</div>' : '' ?>

<?= $document ?>

    <script src="script.js" defer></script>
</body>
</html>
`;

  files['style.css'] = css;
  files['script.js'] = js;
  files['auth.php'] = `${PHP_AUTH}\n`;
  files['search.php'] = `${PHP_SEARCH}\n`;
  files['.htaccess'] = HTACCESS;

  if (options.customHTML && options.customHTML.trim()) {
    files['partials/custom-html.html'] = options.customHTML;
  }

  if (hasTables) {
    files['db.php'] = `<?php
/**
 * PDO connection (MySQL / MariaDB).
 * Credentials are read from environment variables when available.
 */
$dsn = sprintf(
    'mysql:host=%s;port=%s;dbname=%s;charset=utf8mb4',
    getenv('DB_HOST') ?: 'localhost',
    getenv('DB_PORT') ?: '3306',
    '${phpString(databaseSchema.dbName)}'
);

$options = [
    PDO::ATTR_ERRMODE            => PDO::ERRMODE_EXCEPTION,
    PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
    PDO::ATTR_EMULATE_PREPARES   => false,
];

try {
    $pdo = new PDO($dsn, getenv('DB_USER') ?: 'root', getenv('DB_PASS') ?: '', $options);
} catch (PDOException $e) {
    throw new RuntimeException('Database connection failed: ' . $e->getMessage(), (int) $e->getCode());
}
`;
    files['migration.sql'] = generateMigrationSQL(databaseSchema, 'mysql');
    files['data/.gitkeep'] = '';
  } else {
    files['data/.gitkeep'] = '';
  }

  files['README.md'] = `# ${title}

Static PHP site generated by **WebCraft Pro**.

## Run locally

\`\`\`bash
php -S localhost:8000
\`\`\`

Then open http://localhost:8000

## Deploy

Upload every file to the document root of any PHP 7.4+ host. \`style.css\` and
\`script.js\` are static assets; \`index.php\` renders the page.

## Forms

Every \`.wb-root form\` posts back to \`index.php\`, which appends the submission
to \`data/submissions.csv\`. Point a form at your own endpoint by setting its
**URL / Href** in the builder instead.

## Search

The **Search Form** widget is backed by \`search.php\`: the page is split into
its sections, cached in \`data/search-index.json\` and searched with
title-weighted scoring. \`?s=your+word\` renders highlighted results.

${
  hasTables
    ? `## Database

\`migration.sql\` creates the ${databaseSchema.tables.length} table(s) designed in the builder:

\`\`\`bash
mysql -u root -p < migration.sql
\`\`\`

\`db.php\` exposes a ready-to-use PDO \`\$pdo\` connection.
`
    : ''
}
## Custom code

Anything you wrote in the **Code** tab lives in \`style.css\` (CSS), \`script.js\`
(JavaScript) and \`partials/custom-html.html\` (HTML).
`;

  return files;
}
