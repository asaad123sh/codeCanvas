import type { DatabaseSchema, DBColumn, DBTable } from '../types';
import type { SqlDialect } from './sqlDialect';

type Dialect = SqlDialect;

function quoteIdent(name: string, dialect: Dialect): string {
  const safe = name.replace(/[^a-zA-Z0-9_]/g, '_');
  if (dialect === 'mysql') return `\`${safe}\``;
  if (dialect === 'mssql') return `[${safe}]`;
  return `"${safe}"`;
}

function columnType(col: DBColumn, dialect: Dialect): string {
  const type = String(col.type || 'VARCHAR').toUpperCase();
  const length = col.length;

  if (type === 'ENUM') {
    const values = (col.enumValues || ['value'])
      .map((v) => `'${String(v).replace(/'/g, "''")}'`)
      .join(', ');
    if (dialect === 'mysql') return `ENUM(${values})`;
    return 'TEXT';
  }

  if (type === 'DECIMAL') return `DECIMAL(${col.length || 10}, 2)`;
  if (type === 'BIGINT') return dialect === 'mysql' ? 'BIGINT' : 'BIGINT';

  if (dialect === 'mssql') {
    switch (type) {
      case 'VARCHAR':
        return `NVARCHAR(${length || 255})`;
      case 'TEXT':
      case 'LONGTEXT':
        return 'NVARCHAR(MAX)';
      case 'INT':
        return col.autoIncrement && col.primaryKey ? 'INT IDENTITY(1,1)' : 'INT';
      case 'BIGINT':
        return col.autoIncrement && col.primaryKey ? 'BIGINT IDENTITY(1,1)' : 'BIGINT';
      case 'DOUBLE':
        return 'FLOAT';
      case 'BOOLEAN':
        return 'BIT';
      case 'DATETIME':
        return 'DATETIME2';
      case 'JSON':
        return 'NVARCHAR(MAX)';
      case 'BLOB':
        return 'VARBINARY(MAX)';
      default:
        return type;
    }
  }

  if (dialect === 'sqlite') {
    if (type === 'BOOLEAN') return 'INTEGER';
    if (type === 'JSON' || type === 'BLOB') return 'TEXT';
    if (type === 'DOUBLE') return 'REAL';
    if (type === 'DATETIME' || type === 'TIMESTAMP') return 'TEXT';
    if (type === 'INT' || type === 'BIGINT' || type === 'FLOAT' || type === 'DECIMAL') return 'INTEGER';
    if (type === 'VARCHAR') return `TEXT`;
    return type;
  }

  if (dialect === 'postgresql') {
    switch (type) {
      case 'VARCHAR':
        return `VARCHAR(${length || 255})`;
      case 'TEXT':
      case 'LONGTEXT':
        return 'TEXT';
      case 'INT':
        return col.autoIncrement && col.primaryKey ? 'SERIAL' : 'INTEGER';
      case 'FLOAT':
        return 'REAL';
      case 'DOUBLE':
        return 'DOUBLE PRECISION';
      case 'BOOLEAN':
        return 'BOOLEAN';
      case 'DATE':
        return 'DATE';
      case 'DATETIME':
      case 'TIMESTAMP':
        return 'TIMESTAMP';
      case 'JSON':
        return 'JSONB';
      case 'BLOB':
        return 'BYTEA';
      default:
        return type;
    }
  }

  switch (type) {
    case 'VARCHAR':
      return `VARCHAR(${length || 255})`;
    case 'BOOLEAN':
      return 'TINYINT(1)';
    default:
      return length ? `${type}(${length})` : type;
  }
}

function defaultValue(col: DBColumn, dialect: Dialect): string {
  const raw = col.defaultValue;
  if (raw === undefined || raw === null || raw === '') return '';
  if (/^current_timestamp(\(\))?$/i.test(raw)) return ' DEFAULT CURRENT_TIMESTAMP';
  if (['NULL', 'TRUE', 'FALSE'].includes(raw.toUpperCase())) return ` DEFAULT ${raw.toUpperCase()}`;
  if (['INT', 'BIGINT', 'FLOAT', 'DOUBLE', 'DECIMAL'].includes(String(col.type).toUpperCase())) {
    return ` DEFAULT ${raw}`;
  }
  if (dialect === 'sqlite' && /^(NULL|TRUE|FALSE)$/i.test(raw)) {
    return ` DEFAULT ${raw.toUpperCase()}`;
  }
  if (dialect === 'mssql' && /^(NULL|0|1)$/i.test(raw)) {
    return ` DEFAULT ${raw}`;
  }
  return ` DEFAULT '${String(raw).replace(/'/g, "''")}'`;
}

export function generateMigrationSQL(schema: DatabaseSchema, dialect: Dialect): string {
  const lines: string[] = [
    '-- ------------------------------------------------------------',
    '-- Generated by WebCraft Pro',
    `-- Dialect: ${dialect}`,
    '-- ------------------------------------------------------------',
    '',
  ];

  const dbName = schema.dbName.replace(/[^a-zA-Z0-9_]/g, '_') || 'my_website_db';
  if (dialect === 'mysql') {
    lines.push(`CREATE DATABASE IF NOT EXISTS \`${dbName}\` DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;`);
    lines.push(`USE \`${dbName}\`;`);
    lines.push('');
  } else if (dialect === 'mssql') {
    lines.push(`IF DB_ID('${dbName}') IS NULL CREATE DATABASE [${dbName}];`);
    lines.push(`USE [${dbName}];`);
    lines.push('GO', '');
  } else if (dialect === 'sqlite') {
    lines.push(`-- SQLite: the file itself is the database (${dbName}.sqlite).`);
    lines.push('PRAGMA foreign_keys = ON;', '');
  } else {
    lines.push(`-- Create the database first: CREATE DATABASE "${dbName}";`);
    lines.push('');
  }

  const tables = schema.tables || [];

  for (const table of tables) {
    const tName = quoteIdent(table.name, dialect);
    lines.push(`CREATE TABLE IF NOT EXISTS ${tName} (`);

    const body: string[] = [];
    const keys: string[] = [];

    for (const col of table.columns) {
      const colName = quoteIdent(col.name, dialect);
      let def = `  ${colName} ${columnType(col, dialect)}`;

      const isSerial =
        (dialect === 'postgresql' || dialect === 'sqlite') &&
        col.primaryKey &&
        col.autoIncrement;
      if (!isSerial) {
        if (!col.nullable) def += ' NOT NULL';
        if (col.unique) def += ' UNIQUE';
        def += defaultValue(col, dialect);
        if (col.autoIncrement && dialect === 'mysql') def += ' AUTO_INCREMENT';
        if (col.autoIncrement && dialect === 'sqlite') def += ' AUTOINCREMENT';
      }
      body.push(def);

      if (col.primaryKey) keys.push(`  PRIMARY KEY (${colName})`);
      else if (col.autoIncrement && dialect === 'postgresql') {
        // SERIAL implies a sequence; nothing extra to declare.
      }

      if (col.foreignKey?.table && col.foreignKey?.column) {
        const fkTable = quoteIdent(col.foreignKey.table, dialect);
        const fkCol = quoteIdent(col.foreignKey.column, dialect);
        keys.push(
          `  CONSTRAINT ${quoteIdent(`fk_${table.name}_${col.name}`, dialect)} FOREIGN KEY (${colName}) REFERENCES ${fkTable} (${fkCol}) ON DELETE CASCADE`
        );
      }
    }

    const all = [...body, ...keys].join(',\n');
    lines.push(all);
    const engine =
      dialect === 'mysql'
        ? `\n) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;`
        : '\n);';
    lines.push(engine);
    lines.push('');
  }

  if (tables.length === 0) {
    lines.push('-- No tables defined yet. Design them in the Database tab of the builder.');
    lines.push('');
  }

  return lines.join('\n');
}

const MONGO_TYPES: Record<string, string> = {
  VARCHAR: 'String',
  TEXT: 'String',
  LONGTEXT: 'String',
  INT: 'Number',
  BIGINT: 'Number',
  FLOAT: 'Number',
  DOUBLE: 'Number',
  DECIMAL: 'Number',
  BOOLEAN: 'Boolean',
  DATE: 'Date',
  DATETIME: 'Date',
  TIMESTAMP: 'Date',
  JSON: 'Object',
  BLOB: 'String',
  ENUM: 'String',
};

export function mongoTypeFor(sqlType: string): string {
  return MONGO_TYPES[String(sqlType || '').toUpperCase()] || 'String';
}

function pascalCase(name: string): string {
  const safe = name.replace(/[^a-zA-Z0-9_]/g, '') || 'Model';
  return safe.charAt(0).toUpperCase() + safe.slice(1);
}

export function generateMongooseModel(table: DBTable): string {
  const name = pascalCase(table.name);
  const fields = table.columns
    .map((col) => {
      const key = col.name.replace(/[^a-zA-Z0-9_]/g, '_');
      const type = mongoTypeFor(String(col.type));
      const required = col.nullable === false ? ', required: true' : '';
      const unique = col.unique ? ', unique: true' : '';
      const fallback = col.defaultValue ? `, default: ${JSON.stringify(col.defaultValue)}` : '';
      return `  ${key}: { type: ${type}${required}${unique}${fallback} }`;
    })
    .join(',\n');

  return [
    "const mongoose = require('mongoose');",
    '',
    `const ${name}Schema = new mongoose.Schema({`,
    fields,
    '}, { timestamps: true });',
    '',
    `module.exports = mongoose.model('${table.name}', ${name}Schema);`,
    '',
  ].join('\n');
}

export function generateMongooseIndex(schema: DatabaseSchema): string {
  const tables = schema.tables || [];
  if (tables.length === 0) {
    return [
      '/**',
      ' * Design collections in the Database tab of the builder to generate models.',
      ' */',
      'module.exports = {};',
      '',
    ].join('\n');
  }

  const requires = tables
    .map((table) => `const ${pascalCase(table.name)} = require('./${table.name}');`)
    .join('\n');
  const exportsList = tables.map((table) => `  ${pascalCase(table.name)},`).join('\n');

  return [
    '/** Auto-generated model registry */',
    requires,
    '',
    'module.exports = {',
    exportsList,
    '};',
    '',
  ].join('\n');
}

