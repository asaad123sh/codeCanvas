import { usersTable, searchDocumentsTable } from './sqlDialect';

/**
 * Full schema file for any supported database.
 *
 * `includeUsers` adds the `users` table the shipped authentication backend
 * expects, so the SQL a user exports lines up with the login widget instead of
 * being an unrelated list of tables.
 */
export function generateSchemaFile(
  schema: DatabaseSchema,
  dialect: SqlDialect,
  options: { includeUsers?: boolean; includeSearch?: boolean } = {}
): string {
  if (dialect === 'mongodb') {
    const models = (schema.tables || []).map(generateMongooseModel);
    return [
      '// Generated by WebCraft Pro — Mongoose models',
      `// Database: ${schema.dbName}`,
      '',
      ...(models.length ? models : ["module.exports = {}; // design collections in the Database tab"]),
    ].join('\n');
  }

  const includeUsers = options.includeUsers !== false;
  const includeSearch = options.includeSearch === true;
  const designed = schema.tables || [];
  const hasUsers = designed.some((t) => t.name.toLowerCase() === 'users');
  const hasSearch = designed.some((t) => t.name.toLowerCase() === 'search_documents');

  const extra: DBTable[] = [];
  if (includeUsers && !hasUsers) extra.push(usersTable());
  if (includeSearch && !hasSearch) extra.push(searchDocumentsTable());

  const merged: DatabaseSchema = extra.length ? { ...schema, tables: [...designed, ...extra] } : schema;

  const notes: string[] = [];
  if (includeUsers && !hasUsers) notes.push("-- The users table above matches the login widget's auth backend.");
  if (includeSearch && !hasSearch) notes.push('-- Optional: the Search Form widget indexes into a cached JSON file by default; use this table to move that index into SQL.');

  const sql = generateMigrationSQL(merged, dialect);
  return notes.length ? `${sql}\n${notes.join('\n')}\n` : sql;
}
