/** URL/file-safe slug: lowercase words joined by dashes. */
export function slugify(value: string): string {
  return String(value || '')
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60);
}

/** Nav and footer documents never become files, so they keep a reserved slug. */
const RESERVED_SLUGS = new Set(['_nav', '_footer']);

function uniqueSlug(desired: string, pages: SitePage[], exceptId?: string): string {
  const base = RESERVED_SLUGS.has(desired) || !desired ? desired || 'page' : desired;
  let candidate = base;
  let n = 2;
  while (pages.some((p) => p.id !== exceptId && p.config.slug === candidate)) {
    candidate = `${base}-${n++}`;
  }
  return candidate;
}

function makePage(name: string, role: PageRole, pages: SitePage[]): SitePage {
  const id = generateId();
  const slug =
    role === 'nav' ? '_nav' : role === 'footer' ? '_footer' : uniqueSlug(slugify(name), pages);
  return {
    id,
    role,
    name,
    config: {
      ...defaultPageConfig,
      title: name,
      slug,
    },
    elements: {},
    rootIds: [],
    isHome: role === 'page' && !pages.some((p) => p.isHome),
  };
}

/** The starting site: Home + a nav bar document + a footer document. */
function initialPages(): SitePage[] {
  const home = makePage('Home', 'page', []);
  const nav = makePage('Nav Bar', 'nav', [home]);
  const footer = makePage('Footer', 'footer', [home, nav]);
  return [home, nav, footer];
}

/** Every non-nav/footer page, home first — the order the Pages menu shows. */
export function contentPages(pages: SitePage[]): SitePage[] {
  const content = pages.filter((p) => p.role === 'page');
  const home = content.filter((p) => p.isHome);
  const rest = content.filter((p) => !p.isHome);
  return [...home, ...rest];
}

export function navPage(pages: SitePage[]): SitePage | undefined {
  return pages.find((p) => p.role === 'nav');
}

export function footerPage(pages: SitePage[]): SitePage | undefined {
  return pages.find((p) => p.role === 'footer');
}

const HISTORY_LIMIT = 100;
const COALESCE_MS = 700;

/** Mode restored by the top-bar toggle when free drag is switched on again. */
let lastPositionMode: PositionMode = 'offset';

/**
 * Merge a style patch into an element for one breakpoint.
 *
 * Empty values delete the key: on tablet/mobile the breakpoint override is
 * dropped so the value falls back to the desktop style (Elementor-style
 * cascade), and on desktop the dead declaration disappears from the export.
 */
function writeStyles(
  elements: Record<string, ElementNode>,
  id: string,
  styles: Partial<StyleProps>,
  device?: string
): Record<string, ElementNode> {
  const el = elements[id];
  if (!el) return elements;

  const patch: Record<string, unknown> = {};
  const cleared: string[] = [];
  for (const [key, value] of Object.entries(styles || {})) {
    if (value === undefined || value === null || value === '') cleared.push(key);
    else patch[key] = value;
  }

  const next = { ...elements };
  if (device === 'tablet' || device === 'mobile') {
    const responsiveKey = device as 'tablet' | 'mobile';
    const merged: Record<string, unknown> = { ...(el.responsive?.[responsiveKey] || {}), ...patch };
    cleared.forEach((key) => delete merged[key]);
    next[id] = { ...el, responsive: { ...el.responsive, [responsiveKey]: merged } };
  } else {
    const merged: Record<string, unknown> = { ...el.styles, ...patch };
    cleared.forEach((key) => delete merged[key]);
    // Offsets tracked for free drag stay in sync with the CSS they write.
    if ('left' in patch || 'top' in patch || 'marginLeft' in patch || 'marginTop' in patch) {
      const x = parsePx(merged.left ?? merged.marginLeft);
      const y = parsePx(merged.top ?? merged.marginTop);
      next[id] = { ...el, styles: merged, position: { x: x || 0, y: y || 0 } };
    } else {
      next[id] = { ...el, styles: merged };
    }
  }
  return next;
}

function snapshot(state: BuilderState): HistoryEntry {
  return {
    elements: structuredClone(state.elements),
    rootIds: [...state.rootIds],
    pageId: state.activePageId,
  };
}

/**
 * Push the current document onto the undo stack.
 * Passing a non-empty key coalesces rapid successive edits of the same target
 * (typing, slider drags) into a single undo step; passing '' always pushes.
 */
function pushHistory(state: BuilderState, key: string) {
  const now = Date.now();
  const shouldCoalesce = key !== '' && state.historyKey === key && now - state.historyTime < COALESCE_MS;
  if (shouldCoalesce) {
    return {
      history: { past: state.history.past, future: [] },
      historyKey: key,
      historyTime: now,
    };
  }
  const past = [...state.history.past, snapshot(state)];
  if (past.length > HISTORY_LIMIT) past.shift();
  return {
    history: { past, future: [] },
    historyKey: key,
    historyTime: now,
  };
}

function removeElementRecursive(
  elements: Record<string, ElementNode>,
  rootIds: string[],
  id: string
) {
  const el = elements[id];
  if (!el) return;
  for (const childId of el.children || []) {
    removeElementRecursive(elements, rootIds, childId);
  }
  if (el.parentId && elements[el.parentId]) {
    elements[el.parentId] = {
      ...elements[el.parentId],
      children: elements[el.parentId].children.filter((c) => c !== id),
    };
  } else {
    const idx = rootIds.indexOf(id);
    if (idx > -1) rootIds.splice(idx, 1);
  }
  delete elements[id];
}

/** Is `candidateId` the ancestor of (or equal to) `ancestorId`'s target? */
function isDescendant(
  elements: Record<string, ElementNode>,
  ancestorId: string,
  candidateId: string | null
): boolean {
  let current = candidateId;
  const seen = new Set<string>();
  while (current) {
    if (current === ancestorId) return true;
    if (seen.has(current)) return false;
    seen.add(current);
    current = elements[current]?.parentId ?? null;
  }
  return false;
}

function cloneSubtree(
  elements: Record<string, ElementNode>,
  id: string,
  newParentId: string | null
): string {
  const original = elements[id];
  if (!original) return '';
  const newId = generateId();
  const cloned: ElementNode = {
    ...structuredClone(original),
    id: newId,
    parentId: newParentId,
    children: [],
    label: original.label,
  };
  elements[newId] = cloned;
  for (const childId of original.children || []) {
    const newChildId = cloneSubtree(elements, childId, newId);
    if (newChildId) cloned.children.push(newChildId);
  }
  return newId;
}

function collectSubtree(elements: Record<string, ElementNode>, id: string): ElementNode[] {
  const out: ElementNode[] = [];
  const walk = (currentId: string) => {
    const el = elements[currentId];
    if (!el) return;
    out.push(structuredClone(el));
    (el.children || []).forEach(walk);
  };
  walk(id);
  return out;
}

