const STORAGE_KEY = 'webcraft-builder-v1';
let pendingWrite: { key: string; value: string } | null = null;
let writeTimer: ReturnType<typeof setTimeout> | null = null;

function flushStorage() {
  if (pendingWrite) {
    try {
      localStorage.setItem(pendingWrite.key, pendingWrite.value);
    } catch {
      /* quota exceeded — ignore */
    }
    pendingWrite = null;
  }
}

if (typeof window !== 'undefined') {
  window.addEventListener('beforeunload', flushStorage);
  document.addEventListener('visibilitychange', () => {
    if (document.visibilityState === 'hidden') flushStorage();
  });
}

const debouncedStorage = {
  getItem: (name: string): string | null => {
    try {
      const raw = localStorage.getItem(name);
      if (!raw) return null;
      JSON.parse(raw); // validate — never hand malformed data to the store
      return raw;
    } catch {
      try {
        localStorage.removeItem(name);
      } catch {
        /* ignore */
      }
      return null;
    }
  },
  setItem: (name: string, value: string) => {
    pendingWrite = { key: name, value };
    if (writeTimer) clearTimeout(writeTimer);
    writeTimer = setTimeout(flushStorage, 400);
  },
  removeItem: (name: string) => {
    pendingWrite = null;
    try {
      localStorage.removeItem(name);
    } catch {
      /* ignore */
    }
  },
};

